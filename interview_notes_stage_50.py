def _print_welcome_banner() -> None:
    """Выводит приветственное сообщение и краткое описание приложения."""
    title = "InterviewNotes"
    print("=" * 40)
    print(title.center(40))
    print("=" * 40)
    print("Органайзер для подготовки и анализа собеседований.")
    print("Управление кандидатами, вопросами, оценками и итогами.")
    print("=" * 40)


def _print_menu() -> None:
    """Выводит интерактивное меню главного экрана приложения."""
    print("\nЧто хотите сделать?")
    print("  1. Управление кандидатами")
    print("  2. Управление вопросами")
    print("  3. Управление оценками")
    print("  4. Просмотр итогов собеседований")
    print("  5. Выход")
    choice = input("Введите номер действия: ").strip()
    return choice


def _confirm_action(prompt: str) -> bool:
    """Запрашивает подтверждение у пользователя и возвращает результат."""
    answer = input(prompt).strip().lower()
    return answer in {"y", "yes"}
